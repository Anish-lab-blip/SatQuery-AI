"""A synthetic benchmark adapter, for proving the runner works.

WHY THIS EXISTS, AND WHY IT IS DANGEROUS
----------------------------------------
There has to be SOME adapter that returns samples, or the runner's evaluation
path can never be exercised and nobody can tell whether it works. But an adapter
that returns synthetic samples is exactly the thing that produces a fabricated
benchmark score if its status is not recorded.

The resolution is that the status is recorded, structurally:

  * This adapter's corpus IS present by construction (it generates it), so it
    reports `available=True` and would otherwise be scored as REAL.
  * It therefore overrides nothing about status -- instead it deliberately
    reports `is_official() == False`, and the runner maps a non-official adapter
    to `BenchmarkStatus.FIXTURE`.
  * `BenchmarkStatus.FIXTURE.is_scored` is False, so `real_metrics` in the
    report stays empty and no fixture number can be quoted as a benchmark score.

The generation is deterministic and parameterised: `samples` are produced from a
seeded RNG, so the same fixture yields the same numbers on every machine and the
runner's own tests are stable.

The generated task is deliberately trivial (a bimodal score whose sign indicates
the class). It is not a proxy for any real benchmark and does not try to be. Its
only job is to make the evaluation pipeline observable end to end.
"""

from __future__ import annotations

import random
from pathlib import Path
from typing import Any

from core.code_revision import REPO_ROOT
from evaluation.benchmark_adapters.base import (
    BenchmarkAdapter,
    BenchmarkNotAvailableError,
    BenchmarkSample,
    BenchmarkSource,
    CorpusDescription,
)

__all__ = ["SyntheticVQAAdapter"]


class SyntheticVQAAdapter(BenchmarkAdapter):
    """A deterministic, self-generating VQA-shaped benchmark fixture.

    Emits samples whose gold answer is a yes/no string and whose payload holds a
    logit pair. A trivial predictor (sign of the logit difference) scores it, so
    the runner can be exercised without any model, any torch, and any dataset.
    """

    name = "synthetic_vqa_fixture"

    source = BenchmarkSource(
        name="synthetic_vqa_fixture",
        root=REPO_ROOT / "evaluation" / "benchmark_adapters",
        citation="N/A -- generated in-process; not a published benchmark",
        note=(
            "Material is generated by this module from a seeded RNG. It is NOT a "
            "benchmark and its scores carry BenchmarkStatus.FIXTURE."
        ),
    )

    #: Answers the fixture alternates between.
    ANSWERS: tuple[str, str] = ("yes", "no")

    def __init__(
        self,
        *,
        n_samples: int = 32,
        seed: int = 1234,
        accuracy: float = 0.75,
        split: str = "test",
    ) -> None:
        if n_samples < 1:
            raise BenchmarkNotAvailableError(
                f"a fixture needs at least one sample, got {n_samples}"
            )
        if not 0.0 <= accuracy <= 1.0:
            raise BenchmarkNotAvailableError(
                f"fixture accuracy must be in [0,1], got {accuracy}"
            )
        self.n_samples = n_samples
        self.seed = seed
        self.accuracy = accuracy
        self.split = split

    # -- corpus ------------------------------------------------------------
    def describe_corpus(self) -> CorpusDescription:
        """The fixture is always present, and says so as a fixture.

        `available` is True because samples genuinely can be produced. The
        honesty is carried by `is_official` and by the resulting FIXTURE status,
        not by claiming the corpus is missing -- a fixture that lied about being
        unavailable would be no more useful than one that lied about being real.
        """
        return CorpusDescription(
            benchmark=self.name,
            available=True,
            root=str(self.source.root),
            n_files=0,
            bytes=0,
            kinds={"origin": "generated in-process"},
            reason=None,
            note=(
                f"generated in-process (not measured from any benchmark): "
                f"n_samples={self.n_samples}, seed={self.seed}, "
                f"target_accuracy={self.accuracy}. Scores carry status FIXTURE."
            ),
        )

    def is_official(self) -> bool:
        """Always False. This is what turns a score into FIXTURE, not REAL."""
        return False

    def metric_names(self) -> tuple[str, ...]:
        return ("accuracy",)

    # -- loading -----------------------------------------------------------
    def load(self, *, split: str = "test") -> list[BenchmarkSample]:
        """Generate the fixture's samples deterministically."""
        rng = random.Random(f"{self.seed}:{self.n_samples}:{self.accuracy}:{split}")
        samples: list[BenchmarkSample] = []

        for index in range(self.n_samples):
            gold = self.ANSWERS[index % len(self.ANSWERS)]
            correct = rng.random() < self.accuracy
            predicted = gold if correct else self.ANSWERS[1 - self.ANSWERS.index(gold)]

            # Encode both as a two-logit vector where index 0 is "yes".
            # A prediction is recoverable from the vector alone, so a scorer needs
            # nothing but the payload -- keeping the fixture self-contained.
            gold_index = self.ANSWERS.index(gold)
            pred_index = self.ANSWERS.index(predicted)
            logits = [-1.0, -1.0]
            logits[pred_index] = 1.0

            samples.append(
                BenchmarkSample(
                    sample_id=f"fixture-{split}-{index:04d}",
                    payload={"logits": logits, "answers": list(self.ANSWERS)},
                    expected=gold,
                    meta={"gold_index": gold_index, "correct_by_construction": correct},
                )
            )

        return samples

    def to_dict(self) -> dict[str, Any]:
        payload = super().to_dict()
        payload["fixture"] = {
            "n_samples": self.n_samples,
            "seed": self.seed,
            "target_accuracy": self.accuracy,
            "disclaimer": (
                "This adapter generates its own material. Any score it produces "
                "has status FIXTURE and must never be reported as a benchmark "
                "result."
            ),
        }
        return payload


def predict_from_payload(sample: BenchmarkSample) -> str:
    """The trivial scorer the fixture's payload is built for.

    Exposed (rather than buried in the fixture) so the runner's tests can drive
    the real scoring path with it, and so it is obvious that the fixture's
    "prediction" involves no model whatsoever.
    """
    logits = sample.payload.get("logits") or []
    answers = sample.payload.get("answers") or []
    if len(logits) != len(answers) or not logits:
        raise ValueError(
            f"fixture payload for {sample.sample_id!r} is malformed: "
            f"{len(logits)} logits vs {len(answers)} answers"
        )
    best = max(range(len(logits)), key=lambda i: logits[i])
    return str(answers[best])
