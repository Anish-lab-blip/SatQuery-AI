def test_regenerating_the_record_reproduces_it(closure):
    """The record must be a pure function of the evidence (modulo the timestamp)."""
    if not RUN1_MANIFEST_PATH.is_file():
        pytest.skip("run 1 manifest not present")
    module = _load_module()
    run1 = json.loads(RUN1_MANIFEST_PATH.read_text(encoding="utf-8"))
    recovery = json.loads(RECOVERY_MANIFEST_PATH.read_text(encoding="utf-8"))
    adjudication = json.loads(ADJUDICATION_PATH.read_text(encoding="utf-8"))

    rebuilt = module.build_closure(run1, recovery, adjudication)
    rebuilt.pop("generated_at")
    original = dict(closure)
    original.pop("generated_at")
    assert rebuilt == original


