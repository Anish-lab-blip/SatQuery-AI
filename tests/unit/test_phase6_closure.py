"""Tests for the Phase 6 closure record.

WHY THIS EXISTS
---------------
Phase 6 closes with a two-sided status: the Run 1 adapter is **usable/verified** but
**acceptance-rejected**. That pairing is easy to degrade later in two opposite ways:

  * someone "tidies" the record into a single `ACCEPTED` because the adapter works; or
  * someone "tidies" it into a plain `REJECTED` and the working adapter is discarded.

Both are failures. These tests re-derive the closure's claims from the evidence files
and fail if the record and the evidence disagree, and they assert that **both**
rejection records survive and that the val-split `ACCEPTED` is still marked as not
final.

The closure record is generated by `scripts/phase6_close.py`, which reads the evidence
rather than restating it. These tests are the independent second pass: they do not
import the record's numbers from the generator, they recompute them from
`test_adjudication.json` and compare.
"""

from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "phase6_close.py"
EVIDENCE_DIR = REPO_ROOT / "artifacts" / "vlm" / "run1_test_recovery"
CLOSURE_PATH = REPO_ROOT / "artifacts" / "vlm" / "phase6_closure.json"
ADJUDICATION_PATH = EVIDENCE_DIR / "test_adjudication.json"
RECOVERY_MANIFEST_PATH = EVIDENCE_DIR / "run_manifest.json"
RUN1_MANIFEST_PATH = Path(r"D:/New folder (2)/New folder (3)/_x/run_manifest.json")


def _load_module():
    spec = importlib.util.spec_from_file_location("phase6_close", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _load(path: Path):
    if not path.is_file():
        pytest.skip(f"evidence not present: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def closure():
    return _load(CLOSURE_PATH)


@pytest.fixture(scope="module")
def adjudication():
    return _load(ADJUDICATION_PATH)


