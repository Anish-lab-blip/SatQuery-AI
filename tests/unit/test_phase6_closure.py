    tampered = json.loads(ADJUDICATION_PATH.read_text(encoding="utf-8"))
    tampered["decision_split"] = "val"
    path = tmp_path / "tampered_split.json"
    path.write_text(json.dumps(tampered), encoding="utf-8")
