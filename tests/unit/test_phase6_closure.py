# 3. the recorded regression is re-derived from the adjudication, not trusted
# ---------------------------------------------------------------------------
def test_failing_class_arithmetic_is_recomputed_from_the_adjudication(closure, adjudication):
    rows = {r["class"]: r for r in adjudication["per_class_test"]}
    counts = adjudication["baseline_test"]["per_class_counts"]
    base = adjudication["baseline_test"]["per_class_accuracy"]
    adap = adjudication["adapted_test"]["per_class_accuracy"]

    for failure in closure["why_acceptance_rejected"]["regression"]["failing_classes"]:
        name = failure["class"]
        n = counts[name]
        b, a = base[name], adap[name]
        drop = (b - a) * 100.0
        lost = round((b - a) * n)
        se = math.sqrt(max(b * (1 - b) + a * (1 - a), 1e-12) / n)
        z = (b - a) / se

        assert failure["n_questions"] == n
        assert failure["drop_pp"] == pytest.approx(drop, abs=1e-3)
        assert failure["lost_questions"] == lost
        assert failure["z"] == pytest.approx(z, abs=1e-3)
        # And it must genuinely fail BOTH halves of v002, not one.
        assert lost >= 4
        assert z >= 1.96
        # The per-class table stores adapted-baseline, so it is the NEGATIVE of the
        # drop. Comparing them without the sign flip is a silent way to pass a wrong
        # number, so assert the sign explicitly.
        assert rows[name]["delta_pp"] == pytest.approx(-drop, abs=1e-2)


def test_exactly_one_class_fails_and_the_counts_are_consistent(closure, adjudication):
    reg = closure["why_acceptance_rejected"]["regression"]
    rows = adjudication["per_class_test"]

    positive = sum(1 for r in rows if r["delta_pp"] > 0)
    zero = sum(1 for r in rows if r["delta_pp"] == 0)

    assert reg["n_classes_total"] == len(rows) == 19
    assert reg["n_classes_improved"] == positive
    assert reg["n_classes_held"] == zero
    assert reg["n_classes_failed"] == 1
    # Guard the claim I got wrong once by hand: it is 16 improved-or-held, not 18.
    assert positive + zero == 16


