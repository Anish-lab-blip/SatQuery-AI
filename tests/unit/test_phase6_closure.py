def test_artifact_verification_records_promoted_adapter_is_not_a_checkpoint(closure):
    """The provenance trap: the promoted weights are neither intermediate checkpoint."""
    av = closure["artifact_verification"]
    if not av["available"]:
        pytest.skip("adapter_verification.json not present")
    promoted = av["promoted_adapter"]
    assert promoted["is_a_checkpoint"] is False
    assert promoted["all_three_digests_distinct"] is True
    assert promoted["sha256"] == av["weights_file_sha256"]
    # Re-derive the finding: the three weight digests must genuinely differ.
    digests = {promoted["sha256"], *promoted["checkpoint_weight_digests"].values()}
    assert len(digests) == 3
    # And the promoted digest is NOT the checkpoint-2000 digest.
    assert promoted["sha256"] != promoted["checkpoint_weight_digests"][
        "checkpoint-2000/adapter_model.safetensors"
    ]


